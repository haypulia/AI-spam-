# промпты для контролируемого преобразования фрагментов электронных писем

from dataset_generator.transformations import (
    get_transformation_description,
)

def build_transformation_prompt(
    text: str,
    transformation: str,
    language: str = "ru",
    email_format: str = "plain_text",
) -> str:
    # создаёт prompt для преобразования одного фрагмента письма

    transformation_description = (
        get_transformation_description(
            transformation
        )
    )

    language_name = {
        "ru": "русском",
        "en": "английском",
    }.get(
        language,
        language,
    )

    if email_format == "html":

        format_rules = """
Фрагмент является частью HTML-письма.

Сохраняй HTML-структуру там, где это необходимо.
Не превращай HTML в Markdown.
Не добавляй Markdown.

Изменяй только текстовое содержимое,
если это возможно.

Не удаляй существующие HTML-теги,
ссылки, атрибуты, URL и другие технические элементы
без необходимости.
"""

    else:

        format_rules = """
Фрагмент является обычным текстом письма.

Не используй HTML.
Не добавляй Markdown-разметку,
если её не было в исходном тексте.
"""

    prompt = f"""
Ты выполняешь контролируемое преобразование
фрагмента электронного письма.

Тебе передан ОДИН конкретный фрагмент
существующего письма.

Ты НЕ видишь остальные части письма.

Твоя задача — преобразовать ТОЛЬКО переданный фрагмент.

Язык результата:
{language_name}

Тип преобразования:
{transformation}

ТРЕБОВАНИЯ К ПРЕОБРАЗОВАНИЮ:
{transformation_description}

{format_rules}

============================================================
СТРОГИЕ ОГРАНИЧЕНИЯ
============================================================

1. Работай только с текстом между BEGIN TEXT и END TEXT.

2. Не создавай новое письмо.

3. Не продолжай письмо.

4. Не добавляй приветствие, обращение или подпись,
   если их не было в исходном фрагменте.

5. Не добавляй сведения из своего опыта.

6. Не придумывай новые факты.

7. Не придумывай новые даты.

8. Не придумывай новые числа.

9. Не придумывай новые имена.

10. Не придумывай новые организации.

11. Не придумывай новые адреса.

12. Не придумывай новые ссылки.

13. Не меняй номера заказов,
    идентификаторы и другие конкретные значения.

14. Сохраняй фактическое содержание,
    если выбранный transformation явно
    не требует удаления второстепенной информации.

15. Не объясняй свои действия.

16. Не добавляй комментарии.

17. Не используй кавычки вокруг результата.

18. Не пиши вступления вроде:
    "Вот изменённый текст",
    "Конечно",
    "Изменённый вариант",
    "Here is the revised text".

19. Верни ТОЛЬКО преобразованный фрагмент.

20. Не копируй исходный фрагмент полностью.

21. Для transformations, требующих заметного изменения,
    измени несколько предложений.

22. Не ограничивай преобразование
    заменой одного слова или перестановкой
    одного небольшого фрагмента.

23. Сохраняй язык исходного текста.

24. Сохраняй HTML-формат,
    если исходный фрагмент является HTML.

25. Не добавляй информацию из частей письма,
    которых ты не видишь.

============================================================
ПРОВЕРКА ПЕРЕД ОТВЕТОМ
============================================================

Перед тем как ответить, проверь:

- изменён ли исходный фрагмент;
- соответствует ли изменение типу transformation;
- сохранён ли исходный смысл;
- сохранены ли факты;
- сохранены ли даты;
- сохранены ли числа;
- сохранены ли имена;
- сохранены ли организации;
- сохранены ли ссылки;
- не добавлена ли новая информация;
- не добавлены ли приветствие или подпись;
- не создано ли новое письмо;
- не скопирован ли исходный текст без изменений.

Если transformation требует заметного изменения,
проверь, что изменено несколько предложений.

============================================================
ИСХОДНЫЙ ФРАГМЕНТ
============================================================

---BEGIN TEXT---

{text}

---END TEXT---

============================================================

Сейчас верни ТОЛЬКО итоговый преобразованный фрагмент.
"""

    return prompt


def build_source_email_prompt(
    language: str,
    domain: str,
    email_format: str,
) -> str:
    # создаёт prompt для генерации исходного письма

    language_name = (
        "русском"
        if language == "ru"
        else "английском"
    )

    if email_format == "html":

        format_instruction = """
Письмо должно быть настоящим HTML-письмом.

Используй HTML-теги:
<html>, <body>, <div>, <p>, <strong>,
<a>, <ul>, <li>, <br> и другие подходящие теги.

НЕ используй Markdown.

Верни только HTML.
"""

    else:

        format_instruction = """
Письмо должно быть обычным текстом.

НЕ используй HTML.
НЕ используй Markdown.

Верни только текст письма.
"""

    return f"""
Создай реалистичное электронное письмо
на {language_name} языке.

Тематика:
{domain}

Формат:
{email_format}

{format_instruction}

Письмо должно выглядеть как настоящее письмо.

Оно может содержать:

- тему;
- обращение;
- основной текст;
- конкретные сведения;
- даты;
- числа;
- названия организаций;
- ссылки;
- подпись,

если это естественно для данного домена.

Используй реалистичные,
но вымышленные данные.

Не упоминай искусственный интеллект,
нейросети, генерацию текста
или эту инструкцию.

Не объясняй свои действия.

Не добавляй комментарии.

Верни только готовое письмо.
"""