def get_transformation_description(
    transformation: str,
) -> str:
    # возвращает описание transformation

    if transformation not in TRANSFORMATION_DESCRIPTIONS:
        raise ValueError(
            f"Неизвестный transformation: "
            f"{transformation}"
        )

    return TRANSFORMATION_DESCRIPTIONS[
        transformation
    ]